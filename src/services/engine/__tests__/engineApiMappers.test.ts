/**
 * engineApiMappers — unit tests (task 3-2).
 */

import {
  mapCharacterImageInfo,
  mapCharacterProfile,
  mapConversationMessage,
  mapEmojiAction,
  mapEmotionState,
  mapEntityConfig,
  mapInteraction,
  mapMemory,
} from '../engineApiMappers';
import type {
  ConversationMessageDto,
  EmotionStateDto,
  EntityConfigDto,
  InteractionDto,
  MemoryDto,
} from '../EngineApiClient';

describe('engineApiMappers', () => {
  it('maps a conversation message (blob-free, cursor-agnostic)', () => {
    const dto: ConversationMessageDto = {
      id: 'm1',
      entity_id: 'e1',
      sender_entity_id: 'e2',
      interaction_id: 'i1',
      content: 'hi',
      audio_duration: null,
      message_type: 'text',
      emotional_state_bits: 0,
      is_recon_followup: false,
      is_edited: false,
      created_at: '2026-10-11T10:00:00Z',
      updated_at: '2026-10-11T10:00:00Z',
      deleted_at: null,
      is_pinned: true,
      is_read: false,
    };
    const m = mapConversationMessage(dto);
    expect(m.id).toBe('m1');
    expect(m.audio_data).toBeNull();
    expect(m.is_pinned).toBe(true);
    expect(m.is_read).toBe(false);
    expect(m.created_at).toBeInstanceOf(Date);
    expect(m.created_at.getUTCFullYear()).toBe(2026);
  });

  it('maps an interaction keeping RFC3339 strings (app model uses strings)', () => {
    const dto: InteractionDto = {
      id: 'i1',
      entity_id: 'e1',
      interaction_scope: 'private',
      participant_key: 'e1+e2',
      participant_ids: '["e1","e2"]',
      presence_type: 'phone',
      status: 'active',
      started_at: '2026-10-11T10:00:00Z',
      last_activity_at: '2026-10-11T10:05:00Z',
      ended_at: null,
      metadata: null,
      created_at: '2026-10-11T10:00:00Z',
      updated_at: '2026-10-11T10:05:00Z',
      deleted_at: null,
    };
    const i = mapInteraction(dto);
    expect(i.participant_key).toBe('e1+e2');
    expect(i.started_at).toBe('2026-10-11T10:00:00Z');
    expect(i.deleted_at).toBeNull();
  });

  it('maps an emoji action to the camelCase domain with parsed JSON', () => {
    const a = mapEmojiAction({
      id: 'a1',
      entity_id: 'e1',
      emoji_native: '❤️',
      emotion_effect: '{"joy":0.5}',
      metabolism_vector: '{"joy":1}',
      substitution_text: null,
      auto_generated: true,
      is_default: false,
      deleted_at: null,
      created_at: '2026-10-11T10:00:00Z',
      updated_at: '2026-10-11T10:00:00Z',
    });
    expect(a.emojiNative).toBe('❤️');
    expect(a.emotionEffect).toEqual({ joy: 0.5 });
    expect(a.metabolismVector).toEqual({ joy: 1 });
    expect(a.autoGenerated).toBe(true);
    expect(a.createdAt).toBeInstanceOf(Date);
  });

  it('maps emotion state with nullable crystallize starts', () => {
    const dto = {
      entity_id: 'e1',
      last_update: '2026-10-11T10:00:00Z',
      created_at: '2026-10-11T09:00:00Z',
      updated_at: '2026-10-11T10:00:00Z',
      deleted_at: null,
      joy_intensity: 0.2,
      sadness_intensity: 0,
      trust_intensity: 0,
      disgust_intensity: 0,
      fear_intensity: 0,
      anger_intensity: 0,
      surprise_intensity: 0,
      anticipation_intensity: 0,
      joy_baseline: 0.1,
      sadness_baseline: 0,
      trust_baseline: 0,
      disgust_baseline: 0,
      fear_baseline: 0,
      anger_baseline: 0,
      surprise_baseline: 0,
      anticipation_baseline: 0,
      joy_crystallize_start: '2026-10-11T09:00:00Z',
      sadness_crystallize_start: null,
      trust_crystallize_start: null,
      disgust_crystallize_start: null,
      fear_crystallize_start: null,
      anger_crystallize_start: null,
      surprise_crystallize_start: null,
      anticipation_crystallize_start: null,
      decay_tau: 1,
      high_threshold: 0.7,
      low_threshold: 0.2,
      crystallize_intensity: 0.9,
      crystallize_min_hours: 2,
    } as EmotionStateDto;
    const e = mapEmotionState(dto);
    expect(e.joy_crystallize_start).toBeInstanceOf(Date);
    expect(e.sadness_crystallize_start).toBeNull();
    expect(e.deleted_at).toBeNull();
  });

  it('maps memory dates', () => {
    const dto: MemoryDto = {
      id: 'mem1',
      entity_id: 'e1',
      compaction_level: 1,
      content: 'remembered',
      emotional_state_bits: 3,
      start_date: '2026-10-01T00:00:00Z',
      end_date: null,
      created_at: '2026-10-11T10:00:00Z',
      updated_at: '2026-10-11T10:00:00Z',
      deleted_at: null,
    };
    const m = mapMemory(dto);
    expect(m.compaction_level).toBe(1);
    expect(m.start_date).toBeInstanceOf(Date);
    expect(m.end_date).toBeNull();
  });

  it('maps an entity config (id from the map key) with documented gaps', () => {
    const cfg: EntityConfigDto = {
      character_profile: { id: 'p1', name: 'Aria', description: '', personality: '' },
      modules: {},
      lifecycle_config: '{}',
      alias: 'Aria',
      entity_type: 'ai',
      is_muted: true,
      is_disabled: false,
    };
    const e = mapEntityConfig('Aria-20260101', cfg);
    expect(e.id).toBe('Aria-20260101');
    expect(e.character_profile_id).toBe('p1');
    expect(e.is_muted).toBe(1);
    expect(e.rag_reindex_required).toBe(1); // documented default (payload omits it)
  });

  it('maps a character profile with documented defaults', () => {
    const p = mapCharacterProfile({ id: 'p1', name: 'Aria', description: 'd', personality: 'p' });
    expect(p.name).toBe('Aria');
    expect(p.tags).toBe('[]');
    expect(p.is_favorite).toBe(0); // payload omits is_favorite
    expect(p.created_at).toBeInstanceOf(Date);
  });

  it('maps character image info with optional bytes', () => {
    const img = mapCharacterImageInfo(
      {
        id: 'img1',
        character_profile_id: 'p1',
        mime_type: 'image/png',
        description: '',
        is_primary: true,
        display_order: 0,
      },
      'BASE64',
    );
    expect(img.image_data).toBe('BASE64');
    expect(img.is_primary).toBe(true);
  });
});
