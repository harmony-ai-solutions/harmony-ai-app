/**
 * Emoji actions — management-API-backed repository adapter (task 3-2).
 *
 * Reads: `GET /api/entities/:id/emoji-actions` (default-first, then emoji).
 * Writes (3-1b):
 *   - create/upsert → `POST /api/entities/:id/emoji-actions` (id may be
 *     supplied); update → `PUT .../emoji-actions/:actionId`
 *   - delete all → `DELETE .../emoji-actions`
 *   - delete defaults → `DELETE .../emoji-actions?scope=default`
 *
 * The wire carries `emotion_effect` / `metabolism_vector` as JSON STRINGS (the
 * app's column shape), so the adapter stringifies them.
 *
 * `deleteEmojiAction(actionId)` remains unsupported: the engine route is nested
 * under the entity (`.../entities/:id/emoji-actions/:actionId`) but the app
 * interface carries only the action id (see the 3-2 report's write audit).
 */

import type { EmojiAction } from '../../../database/models';
import { engineApiClient } from '../EngineApiClient';
import { EngineApiUnsupportedError } from '../EngineApiClient';
import type { EmojiActionWriteDto } from '../EngineApiClient';
import { mapEmojiAction } from '../engineApiMappers';

async function fetchActions(entityId: string): Promise<EmojiAction[]> {
  const res = await engineApiClient.entityEmojiActions(entityId);
  return (res.emoji_actions ?? []).map(mapEmojiAction);
}

export async function getEmojiActionsForEntity(
  entityId: string,
): Promise<Map<string, EmojiAction>> {
  const map = new Map<string, EmojiAction>();
  for (const action of await fetchActions(entityId)) {
    map.set(action.emojiNative, action);
  }
  return map;
}

export async function getEmojiAction(
  entityId: string,
  emojiNative: string,
): Promise<EmojiAction | null> {
  const actions = await fetchActions(entityId);
  return actions.find(a => a.emojiNative === emojiNative) ?? null;
}

export async function getAllEmojiActionsArray(entityId: string): Promise<EmojiAction[]> {
  return fetchActions(entityId);
}

export async function countEmojiActions(entityId: string): Promise<number> {
  return (await fetchActions(entityId)).length;
}

// ── Writes ───────────────────────────────────────────────────────────────

/** Domain → wire (stringify the JSON-string columns). */
function toWriteDto(
  action: Omit<EmojiAction, 'createdAt' | 'updatedAt'>,
): EmojiActionWriteDto {
  return {
    id: action.id || undefined,
    emoji_native: action.emojiNative,
    emotion_effect: action.emotionEffect ? JSON.stringify(action.emotionEffect) : null,
    metabolism_vector: action.metabolismVector
      ? JSON.stringify(action.metabolismVector)
      : null,
    substitution_text: action.substitutionText ?? null,
    auto_generated: action.autoGenerated,
    is_default: action.isDefault,
  };
}

export async function createEmojiAction(
  action: Omit<EmojiAction, 'createdAt' | 'updatedAt'>,
): Promise<void> {
  await engineApiClient.createEmojiAction(action.entityId, toWriteDto(action));
}

/**
 * Upsert (app `INSERT OR REPLACE` parity): update the existing action in place,
 * falling back to a create when the id is not present on the entity.
 */
export async function upsertEmojiAction(
  action: Omit<EmojiAction, 'createdAt' | 'updatedAt'>,
): Promise<void> {
  const body = toWriteDto(action);
  try {
    await engineApiClient.updateEmojiAction(action.entityId, action.id, body);
  } catch (e) {
    if (e instanceof Error && 'status' in e && (e as { status: number }).status === 404) {
      await engineApiClient.createEmojiAction(action.entityId, body);
      return;
    }
    throw e;
  }
}

export async function deleteAllEmojiActions(entityId: string): Promise<void> {
  await engineApiClient.deleteEmojiActions(entityId);
}

export async function deleteDefaultEmojiActions(entityId: string): Promise<number> {
  const res = await engineApiClient.deleteEmojiActions(entityId, 'default');
  return res.deleted ?? 0;
}

// ── Delete (engine route is nested under the owning entity) ──────────────

export async function deleteEmojiAction(actionId: string, entityId?: string): Promise<void> {
  let owner = entityId;
  if (!owner) {
    const entities = await engineApiClient.listEntities();
    for (const id of Object.keys(entities)) {
      const actions = await fetchActions(id);
      if (actions.some(a => a.id === actionId)) {
        owner = id;
        break;
      }
    }
  }
  if (!owner) {
    throw new EngineApiUnsupportedError('deleteEmojiAction (owning entity id not found)');
  }
  await engineApiClient.deleteEmojiAction(owner, actionId);
}
