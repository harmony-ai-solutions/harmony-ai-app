/**
 * EngineApi mappers — wire DTO → app domain models (task 3-2).
 *
 * The engine speaks snake_case on the wire and serializes Go `time.Time` as
 * RFC3339 strings and nullable pointers as JSON `null`. The app's domain models
 * (`src/database/models.ts`) are also snake_case for the core tables (they
 * mirror the Go structs byte-for-byte), so most fields pass through; the
 * mapping is chiefly type coercion (RFC3339 string → `Date`, `*bool` → boolean,
 * `*int` → number) plus the emoji-action camelCase projection.
 *
 * Times are parsed defensively: an absent/unparseable timestamp becomes the
 * epoch (never `Invalid Date`) so a mapper can never corrupt a render.
 */

