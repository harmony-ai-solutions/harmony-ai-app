/**
 * Map an entity config (map value / `GET /api/entities/:id`) to the app's
 * `Entity` model. `id` comes from the map key (or the request id).
 *
 * 3-1b: the engine's entity read payload now carries the top-level
 * `character_profile_id`, `rag_reindex_required` and the row timestamps, so the
 * domain row is fully populated.
 */
export function mapEntityConfig(id: string, cfg: EntityConfigDto): Entity {
  return {
    id,
    alias: cfg.alias ?? '',
    character_profile_id: cfg.character_profile_id ?? cfg.character_profile?.id ?? null,
    lifecycle_config: cfg.lifecycle_config ?? null,
    rag_reindex_required: cfg.rag_reindex_required === false ? 0 : 1,
    entity_type: cfg.entity_type ?? 'ai',
    is_muted: cfg.is_muted ? 1 : 0,
    is_disabled: cfg.is_disabled ? 1 : 0,
    character_profile_name: cfg.character_profile?.name ?? null,
    created_at: toDate(cfg.created_at),
    updated_at: toDate(cfg.updated_at),
    deleted_at: toDateOrNull(cfg.deleted_at),
  };
}

